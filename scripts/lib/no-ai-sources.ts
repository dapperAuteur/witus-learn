import type { AuthoredCourse, AuthoredLesson } from "../data/authored-course";

/**
 * The matcher behind `pnpm check:no-ai-sources`: an AI tool is never a source.
 *
 * BAM, 2026-11-09: "no AI sources in courses." Course text and bibliographies may never cite an AI
 * tool or AI output as the authority for a fact. The CREW series research agents (2026-10-26) kept
 * finding brief facts that came from an AI chat and from no source at all (two CREW-07 game-day
 * steps among them); a fact only an AI said is a fact nobody checked. The fetch-or-do-not-cite rules
 * already say where a fact must come from. This closes the gap where the AI itself gets written
 * down as the source.
 *
 * WHAT IT FLAGS: citation and attribution SHAPES, not names. The AI courses name ChatGPT, Claude and
 * Gemini on nearly every page, legitimately, because they teach about them. So a bare name is never
 * a hit. A hit is one of:
 *   - a parenthetical citation whose author is a chatbot or "AI": (ChatGPT, 2026), (Gemini, n.d.)
 *   - a source label naming one: "Source: Gemini", "**Sources:** ChatGPT"
 *   - narrative attribution: "according to Claude", "as reported by an AI"
 *   - a chatbot speaking as the authority: "ChatGPT said", "an AI told us", "Gemini confirms"
 *   - authorship by AI: "generated by AI", "written by ChatGPT", "AI-generated summary"
 *   - "I asked ChatGPT" (the chat as the method of finding the fact)
 *   - a reference entry that IS a chat: author position holds a chatbot, the APA descriptor
 *     "[Large language model]", a chat share link, or "OpenAI. (2023). ChatGPT (Mar 14 version)"
 *
 * WHAT IT LEAVES ALONE ON PURPOSE: the generic "the AI said", "an AI states", "citing the AI". The
 * thirty AI courses say these on most pages while teaching verification ("if the AI said so, check
 * it"), and a course that leaned on an unnamed AI for a fact would still be caught by the rule in
 * CLAUDE.md and by review. The guard flags the NAMED forms, which are the ones a bibliography or an
 * in-text citation actually carries, plus the one generic phrase BAM named, "an AI said".
 *
 * WHAT IT PROTECTS (reported, never failed): text inside quotation marks, a blockquote, or a code
 * fence. A lesson that shows the pattern it warns against is quoting, not citing. The AI research
 * course's "how APA cites ChatGPT" example sits in a blockquote for exactly this reason.
 *
 * Pure: no file I/O. scripts/check-no-ai-sources.ts loads the catalog and prints; the Vitest file
 * feeds this strings.
 */

/** Chatbot and model names that appear in author position when an AI is cited. Vendors (OpenAI,
 *  Anthropic, Google) are NOT here: a vendor's technical report or model card is a document. */
const BOT =
  "(?:ChatGPT|GPT-\\d[\\w.-]*|Claude|Gemini|Copilot|Perplexity|Bard|Grok|DeepSeek|Llama|Mistral|Gemma|Bing\\s+Chat|Meta\\s+AI)";
/** The names that are only ever a chatbot in prose. Bard (Shakespeare), Llama, Mistral (the wind) and
 *  Gemma are common nouns or names too, so in prose they count only in author position (above). */
const BOT_PROSE = "(?:ChatGPT|GPT-\\d[\\w.-]*|Claude|Gemini|Copilot|Perplexity|Grok|DeepSeek|Bing\\s+Chat|Meta\\s+AI|Google\\s+Bard)";
/** Version words that may follow a bot name: "Claude 3.5 Sonnet", "Gemini 1.5 Pro", "GPT-4o mini". */
const VERSION = "(?:\\s+(?:\\d[\\w.]*|o\\d|Pro|Ultra|Advanced|Sonnet|Opus|Haiku|Flash|Plus|Turbo|Mini|Nano|Instant))*";
const BOT_V = `${BOT}${VERSION}`;
const BOT_PROSE_V = `${BOT_PROSE}${VERSION}`;
/** Generic ways of naming the tool as a party: "an AI", "the chatbot", "a language model". */
const GENERIC =
  "(?:[Aa]n?\\s+AI(?:\\s+(?:chatbot|assistant|tool|model))?|[Tt]he\\s+AI(?:\\s+(?:chatbot|assistant|tool|model))?|[Aa]n?\\s+chatbot|[Tt]he\\s+chatbot|[Aa]n?\\s+(?:large\\s+)?language\\s+model|[Tt]he\\s+(?:large\\s+)?language\\s+model|[Aa]n?\\s+LLM|[Tt]he\\s+LLM)";
/** The next word is capitalised: "according to Claude Shannon", "according to AI Index". A surname
 *  or a report title, not a chatbot. */
const NOT_A_NAME = "(?!\\s+[A-Z][a-z])";

export interface AiSourcePattern {
  id: string;
  /** What the shape means, for the report. */
  what: string;
  regex: RegExp;
  /** Only tested on a line shaped like a reference entry (bullet or author-date) or inside a Sources block. */
  referenceOnly?: boolean;
}

