/** A markdown reference-list entry: "- Marks, C. (1989). Title." or "Author. (n.d.)." */
const REFERENCE_LINE = /^\s*(?:[-*]\s+|\d+\.\s+)?[^\n]*\((?:n\.d\.|\d{4}[a-z]?)\)/;
const SOURCES_HEADING = /^\s*#{1,6}\s*(sources|references|further reading|bibliography)\b/i;
const ANY_HEADING = /^\s*#{1,6}\s+/;
const BLOCKQUOTE = /^\s*>/;
const FENCE = /^\s*(```|~~~)/;
/** Spans a match may sit inside and count as quoted: "...", “...”, `...`. */
const QUOTED_SPAN = /"[^"\n]*"|“[^”\n]*”|`[^`\n]*`/g;

export type Protection = "quoted" | "blockquote" | "code block";

export interface AiSourceHit {
  course: string;
  lesson: string;
  /** Which text of the lesson: "body", "quiz[3].explanation", "recall[1].answer", "description". */
  field: string;
  /** 1-based line within that text. */
  line: number;
  pattern: string;
  what: string;
  /** The matched text, trimmed. */
  match: string;
  /** The whole line, trimmed, for the report. */
  text: string;
  /** Inside a `## Sources` block (a bibliography entry) rather than lesson prose. */
  inSources: boolean;
  /** Why this hit does not fail: null means it is a violation unless allowlisted. */
  protection: Protection | null;
}

export interface TextLocation {
  course: string;
  lesson: string;
  field: string;
}

function quotedRanges(line: string): Array<[number, number]> {
  const out: Array<[number, number]> = [];
  for (const m of line.matchAll(QUOTED_SPAN)) out.push([m.index, m.index + m[0].length]);
  return out;
}

/** Every AI-as-source shape in one text, line by line. */
export function scanText(text: string, where: TextLocation): AiSourceHit[] {
  const hits: AiSourceHit[] = [];
  const lines = text.split("\n");
  let inSources = false;
  let inFence = false;
  for (let i = 0; i < lines.length; i++) {
    const line = lines[i];
    if (FENCE.test(line)) {
      inFence = !inFence;
      continue;
    }
    if (SOURCES_HEADING.test(line)) inSources = true;
    else if (inSources && (ANY_HEADING.test(line) || line.trim() === "")) inSources = false;

    const referenceShaped = inSources || REFERENCE_LINE.test(line);
    const quoted = quotedRanges(line);
    for (const p of AI_SOURCE_PATTERNS) {
      if (p.referenceOnly && !referenceShaped) continue;
      p.regex.lastIndex = 0;
      for (const m of line.matchAll(p.regex)) {
        const at = m.index;
        let protection: Protection | null = null;
        if (inFence) protection = "code block";
        else if (BLOCKQUOTE.test(line)) protection = "blockquote";
        else if (quoted.some(([a, b]) => at > a && at < b)) protection = "quoted";
        hits.push({
          ...where,
          line: i + 1,
          pattern: p.id,
          what: p.what,
          match: m[0].trim(),
          text: line.trim(),
          inSources,
          protection,
        });
      }
    }
  }
  return hits;
}

/** Every string a learner can read in a lesson, named so a hit says where it sits. */
export function lessonTexts(lesson: AuthoredLesson): Array<{ field: string; text: string }> {
  const out: Array<{ field: string; text: string }> = [];
  if (lesson.body) out.push({ field: "body", text: lesson.body });
  lesson.quiz?.questions.forEach((q, i) => {
    out.push({ field: `quiz[${i}].prompt`, text: q.prompt });
    q.options.forEach((o, j) => out.push({ field: `quiz[${i}].options[${j}]`, text: o }));
    if (q.explanation) out.push({ field: `quiz[${i}].explanation`, text: q.explanation });
  });
  if (lesson.exercise) {
    if (lesson.exercise.instructions) out.push({ field: "exercise.instructions", text: lesson.exercise.instructions });
    lesson.exercise.items.forEach((it, i) => {
      out.push({ field: `exercise[${i}].prompt`, text: it.prompt });
      if (it.hint) out.push({ field: `exercise[${i}].hint`, text: it.hint });
      if (it.explanation) out.push({ field: `exercise[${i}].explanation`, text: it.explanation });
    });
  }
  lesson.recallContent?.forEach((r, i) => {
    out.push({ field: `recall[${i}].prompt`, text: r.prompt });
    out.push({ field: `recall[${i}].answer`, text: r.answer });
  });
  return out;
}

/** Every hit in a course: its description and every lesson's texts. */
export function scanCourse(slug: string, course: AuthoredCourse): AiSourceHit[] {
  const hits = scanText(course.description ?? "", { course: slug, lesson: "(course)", field: "description" });
  for (const lesson of course.lessons) {
    for (const { field, text } of lessonTexts(lesson)) {
      hits.push(...scanText(text, { course: slug, lesson: lesson.slug, field }));
    }
  }
  return hits;
}

/** A reviewed exception: this exact matched text, in this lesson of this course, with the reason. */
export interface AllowedAiMention {
  course: string;
  lesson: string;
  /** The hit's `match`, exactly. A different phrase in the same lesson is still a violation. */
  match: string;
  reason: string;
}

export function isAllowed(hit: AiSourceHit, allowlist: readonly AllowedAiMention[]): AllowedAiMention | null {
  return allowlist.find((a) => a.course === hit.course && a.lesson === hit.lesson && a.match === hit.match) ?? null;
}

/** Allowlist entries no hit used: fixed content, or a typo in the entry. Either way the entry goes. */
export function staleAllowlist(hits: readonly AiSourceHit[], allowlist: readonly AllowedAiMention[]): AllowedAiMention[] {
  return allowlist.filter((a) => !hits.some((h) => h.course === a.course && h.lesson === a.lesson && h.match === a.match));
}

export function formatHit(h: AiSourceHit): string {
  const where = h.inSources ? "bibliography" : "lesson text";
  const flag = h.protection ? `  (${h.protection}, allowed)` : "";
  return `  ${h.course} / ${h.lesson}  [${h.field}:${h.line}, ${where}]  ${h.pattern}: "${h.match}"${flag}\n      ${h.text.slice(0, 180)}`;
}
