import { describe, expect, it } from "vitest";
import {
  AI_SOURCE_PATTERNS,
  isAllowed,
  lessonTexts,
  scanCourse,
  scanText,
  staleAllowlist,
  type AiSourceHit,
  type AllowedAiMention,
} from "../scripts/lib/no-ai-sources";

/**
 * BAM, 2026-11-09: "no AI sources in courses." The guard (scripts/check-no-ai-sources.ts) must fail a
 * lesson that cites or attributes a fact to an AI tool, and must leave alone a lesson that teaches
 * ABOUT one. These pin both halves and the two protections (quotation marks, blockquote) that let a
 * lesson show the pattern it warns against.
 */

const where = { course: "c", lesson: "l", field: "body" };
const open = (text: string): AiSourceHit[] => scanText(text, where).filter((h) => h.protection === null);
const ids = (text: string): string[] => open(text).map((h) => h.pattern);

describe("citation and attribution shapes fail", () => {
  it("a parenthetical citation whose author is a chatbot or 'AI'", () => {
    expect(ids("The bridge opened in 1932 (ChatGPT, 2026).")).toEqual(["parenthetical"]);
    expect(ids("Prices rose 4% (Claude 3.5 Sonnet, 2025, p. 2).")).toEqual(["parenthetical"]);
    expect(ids("It was founded in 1901 (Gemini, n.d.).")).toEqual(["parenthetical"]);
    expect(ids("The figure is 12 million (AI, 2024).")).toEqual(["parenthetical"]);
    expect(ids("The spec allows 3 amps (GPT-4o, 2024).")).toEqual(["parenthetical"]);
  });

  it("a source label naming an AI", () => {
    expect(ids("Source: Gemini")).toEqual(["source-label"]);
    expect(ids("**Source:** ChatGPT, retrieved May 2026")).toEqual(["source-label"]);
    expect(ids("- Sources: an AI summary of the hearing")).toEqual(["source-label"]);
  });

  it("narrative attribution to an AI", () => {
    expect(ids("According to Claude, the statute passed in 1970.")).toEqual(["according-to"]);
    expect(ids("As reported by an AI assistant, the plant closed in 1988.")).toEqual(["according-to"]);
    expect(ids("The rule, as per Copilot, is 30 days.")).toEqual(["according-to"]);
  });

  it("an AI speaking as the authority", () => {
    expect(ids("ChatGPT said the first race was in 1911.")).toEqual(["bot-said"]);
    expect(ids("An AI told us the cable is rated 75 ohms.")).toEqual(["bot-said"]);
    expect(ids("Gemini confirms the date as 1952.")).toEqual(["bot-said"]);
  });

  it("authorship attributed to an AI", () => {
    expect(ids("This summary was generated by AI.")).toEqual(["generated-by"]);
    expect(ids("The timeline below was written by ChatGPT.")).toEqual(["generated-by"]);
    expect(ids("An AI-generated summary of the ruling follows.")).toEqual(["generated-by"]);
  });

  it("the chat as the method of finding the fact", () => {
    expect(ids("I asked ChatGPT and it gave the 1932 date.")).toEqual(["asked-bot"]);
    expect(ids("We asked an AI for the voltage figures.")).toEqual(["asked-bot"]);
  });

  it("a reference entry that is a chat", () => {
    expect(ids("## Sources\n- ChatGPT. (2026). Answer to a question about cable ratings.")).toEqual(["ref-author-bot"]);
    expect(open("## Sources\n- OpenAI. (2023). *ChatGPT* (Mar 14 version) [Large language model]. https://chat.openai.com/chat").map((h) => h.pattern).sort()).toEqual(
      ["ref-chat-host", "ref-chat-link", "ref-descriptor", "ref-title-bot"],
    );
    expect(ids("- Anthropic. (2025). Claude [Large language model]. https://claude.ai")).toEqual(expect.arrayContaining(["ref-descriptor", "ref-chat-host"]));
    expect(ids("See the conversation at https://chatgpt.com/share/abc123 for the full list.")).toEqual(["ref-chat-link"]);
  });

  it("tags a hit in a Sources block as bibliography and names the line", () => {
    const [hit] = open("Prose line.\n\n## Sources\n- Gemini. (2026). Notes on the 1890 census.");
    expect(hit).toMatchObject({ pattern: "ref-author-bot", inSources: true, line: 4, course: "c", lesson: "l", field: "body" });
    expect(hit.match).toBe("- Gemini. (2026");
  });
});

describe("mentions and documents pass", () => {
  it("a lesson about a tool names it freely", () => {
    expect(open("ChatGPT is a chatbot released by OpenAI in November 2022 (OpenAI, 2022).")).toEqual([]);
    expect(open("Open Gemini, paste the prompt, and compare the two answers.")).toEqual([]);
    expect(open("Claude and Copilot both refuse the request; note the difference in wording.")).toEqual([]);
    expect(open("The course teaches how to spot AI-generated images and deepfakes.")).toEqual([]);
    expect(open("Nothing an AI told you enters your work as a claim until you have verified it against a source you can cite.")).toEqual([]);
  });

  it("a vendor's own document is a source", () => {
    expect(open("## Sources\n- OpenAI. (2023). GPT-4 technical report. https://cdn.openai.com/papers/gpt-4.pdf")).toEqual([]);
    expect(open("## Sources\n- Anthropic. (2024). The Claude 3 model family: Opus, Sonnet, Haiku. https://www.anthropic.com/claude-3-model-card")).toEqual([]);
    expect(open("## Sources\n- Google. (2023). Gemini: A family of highly capable multimodal models. https://arxiv.org/abs/2312.11805")).toEqual([]);
  });

  it("people and things that share a name are not chatbots", () => {
    expect(open("According to Claude Shannon, information is surprise (Shannon, 1948).")).toEqual([]);
    expect(open("The exhibition ran at the Bard Graduate Center (Bard Graduate Center, 2019).")).toEqual([]);
    expect(open("According to the Bard, all the world's a stage.")).toEqual([]);
    expect(open("The copilot said 'V1' and the captain rotated.")).toEqual([]);
    expect(open("A llama produces fibre every year; the mistral blew for three days.")).toEqual([]);
    expect(open("Source: AI Now Institute. (2023). Annual report.")).toEqual([]);
    expect(open("The Gemini Observatory reported the finding (Gemini Observatory, 2021).")).toEqual([]);
  });

  it("a quoted example is a quotation, and a blockquote or code fence is protected", () => {
    const quoted = scanText('Never write "according to ChatGPT" in a paper.', where);
    expect(quoted).toHaveLength(1);
    expect(quoted[0].protection).toBe("quoted");

    const curly = scanText("The WGA clause reads: “materials generated by AI must be disclosed.”", where);
    expect(curly.map((h) => h.protection)).toEqual(["quoted"]);

    const block = scanText("APA's form is:\n\n> OpenAI. (2023). *ChatGPT* (version) [Large language model]. https://chat.openai.com/chat", where);
    expect(block.length).toBeGreaterThan(0);
    expect(block.every((h) => h.protection === "blockquote")).toBe(true);

    const fence = scanText("Try this prompt:\n```\nI asked ChatGPT: summarize the ruling\n```\nThen verify it.", where);
    expect(fence.map((h) => h.protection)).toEqual(["code block"]);
  });

  it("a chat host counts only inside a reference entry", () => {
    expect(open("Launch from https://claude.ai/code and pick the repo.")).toEqual([]);
    expect(ids("- Anthropic. (n.d.). Claude. https://claude.ai")).toEqual(["ref-chat-host"]);
  });
});

describe("the course scan", () => {
  it("reads every learner-visible text and names the field", () => {
    const hits = scanCourse("demo", {
      title: "Demo",
      description: "A course written by ChatGPT.",
      lessons: [
        {
          slug: "one",
          title: "One",
          body: "Fine prose.",
          quiz: {
            questions: [
              { prompt: "When did it open?", options: ["1932", "1933 (ChatGPT, 2026)"], correctIndex: 0, explanation: "According to Gemini, 1932." },
            ],
          },
          recallContent: [{ prompt: "Who said so?", answer: "An AI told us." }],
          exercise: { instructions: "Fill in.", items: [{ prompt: "The ___ opened in 1932.", answer: "bridge", hint: "Source: Copilot" }] },
        },
      ],
    });
    expect(hits.map((h) => `${h.lesson}:${h.field}:${h.pattern}`)).toEqual([
      "(course):description:generated-by",
      "one:quiz[0].options[1]:parenthetical",
      "one:quiz[0].explanation:according-to",
      "one:exercise[0].hint:source-label",
      "one:recall[0].answer:bot-said",
    ]);
  });

  it("lessonTexts lists body, quiz, exercise and recall strings", () => {
    const fields = lessonTexts({
      slug: "x",
      title: "X",
      body: "b",
      quiz: { questions: [{ prompt: "p", options: ["a", "b"], correctIndex: 0, explanation: "e" }] },
      exercise: { items: [{ prompt: "p", answer: "a" }] },
      recallContent: [{ prompt: "p", answer: "a" }],
    }).map((t) => t.field);
    expect(fields).toEqual(["body", "quiz[0].prompt", "quiz[0].options[0]", "quiz[0].options[1]", "quiz[0].explanation", "exercise[0].prompt", "recall[0].prompt", "recall[0].answer"]);
  });
});

describe("the allowlist", () => {
  const hit = open("According to Claude, the statute passed in 1970.")[0];
  const entry: AllowedAiMention = { course: "c", lesson: "l", match: "According to Claude", reason: "teaching example" };

  it("matches course, lesson and the exact phrase", () => {
    expect(isAllowed(hit, [entry])).toBe(entry);
    expect(isAllowed(hit, [{ ...entry, lesson: "other" }])).toBeNull();
    expect(isAllowed(hit, [{ ...entry, match: "according to Claude" }])).toBeNull();
  });

  it("reports an entry no hit uses", () => {
    expect(staleAllowlist([hit], [entry])).toEqual([]);
    expect(staleAllowlist([], [entry])).toEqual([entry]);
  });
});

describe("the pattern table", () => {
  it("every pattern has a stable id and a global regex", () => {
    const seen = new Set<string>();
    for (const p of AI_SOURCE_PATTERNS) {
      expect(seen.has(p.id)).toBe(false);
      seen.add(p.id);
      expect(p.regex.global).toBe(true);
    }
  });
});
